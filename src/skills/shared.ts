/**
 * Текущая дата для промпта.
 *
 * ⚠️ Волатильная часть — не ставить в НАЧАЛО системного промпта: prefix caching
 * сервера инференса кэширует общий префикс, и меняющееся начало даёт промах кэша
 * на каждом запросе.
 */
export function getDateLine(): string {
  const now = new Date();
  const dateStr = now.toLocaleDateString('ru-RU', { year: 'numeric', month: 'long', day: 'numeric' });
  const year = now.getFullYear();
  const prevYear = year - 1;
  return `Текущая дата: ${dateStr}. Используй её как точку отсчёта при анализе трендов, поиске новостей и расчёте периодов. Ищи информацию за ${prevYear}–${year} год, не за более ранние периоды.`;
}

/**
 * Преамбула для КАЖДОГО специалиста (подмешивается в runSpecialist).
 *
 * Даёт общие правила стиля/эмодзи, дату (нужна Трендвотчеру и QBR) и правила чипов —
 * БЕЗ блока suggestions (его добавляет оркестратор отдельным финальным ходом)
 * и БЕЗ навигации/сохранения (это забота оркестратора).
 */
export function getSpecialistPreamble(): string {
  return `${getDateLine()}

${FORMATTING_RULES}

${INTERACTIVE_LINK_RULES}

Не добавляй блоки \`\`\`suggestions\`\`\` или \`\`\`choices\`\`\` — их добавит отдельный финальный шаг.`;
}
