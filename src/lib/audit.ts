/**
 * Отправка событий аудита (требование ИБ: кто, когда, что изменил, старое → новое).
 *
 * Вызывать из КАЖДОГО места, где пользователь меняет конфигурацию: настройки
 * профиля и уведомлений, интеграции, включение/выключение агентов и ИИ-сервисов,
 * права доступа. Сейчас реально существует одна такая точка — переключение темы,
 * остальные разделы ещё заглушки (см. README, раздел «Аудит-лог»).
 *
 * Что НЕ нужно передавать: кто и когда. Субъект сервер берёт из токена, время
 * ставит своё — значения с клиента можно подделать, поэтому они игнорируются.
 *
 * Список допустимых значений `action` — AUDIT_ACTIONS в scripts/lib/audit.ts.
 * Новое действие сначала добавляется туда, иначе сервер ответит 400.
 */
import { getToken } from '../features/auth/auth';

export interface AuditRecord {
  /** Действие из контролируемого словаря, напр. 'settings.theme.change'. */
  action: string;
  /** Что меняли: раздел, сущность. */
  target: string;
  /** Идентификатор конкретного объекта, если есть. */
  targetId?: string;
  /** Значение до изменения. */
  before?: unknown;
  /** Значение после изменения. */
  after?: unknown;
}

/**
 * Отправляет событие, не блокируя интерфейс.
 *
 * ⚠️ Сейчас неудачная отправка НЕ отменяет изменение настройки — оно уже применено
 * локально. Если ИБ потребует «без записи в журнал изменение не применяется»,
 * эту функцию надо делать блокирующей, а вызывающий код — откатывающим действие
 * при ошибке.
 */
export function recordAudit(record: AuditRecord): void {
  const token = getToken();
  // До входа в приложение записывать нечего: субъекта нет.
  if (!token) return;

  void fetch('/api/audit', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${token}`,
    },
    body: JSON.stringify(record),
    keepalive: true,
  })
    .then((res) => {
      if (!res.ok) console.error('[audit] событие не записано, статус', res.status);
    })
    .catch((err: unknown) => {
      console.error('[audit] событие не отправлено', err);
    });
}
